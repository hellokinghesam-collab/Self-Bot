"""
plugins/aa_owner_wide_access.py
---------------------------------
این پلاگین، **بدون تغییر دادن هیچ فایل دیگری در پروژه**، سیاست امنیتی مرکزی
پروژه (تابع is_authorized در security.py) را در زمان اجرا (runtime) با یک
نسخه‌ی جدید و امن جایگزین می‌کند. هدف: اجازه دادن به اجرای دستورات از
**هر چتی** (نه فقط Saved Messages)، اما فقط وقتی خودِ owner واقعی اکانت آن
دستور را فرستاده باشد.

⚠️ چرا این کار امن است؟
  تابع اصلی is_authorized دو شرط داشت: (۱) فرستنده خودِ صاحب اکانت باشد،
  (۲) چت مقصد Saved Messages باشد. نسخه‌ی جدید فقط شرط (۲) را حذف می‌کند و
  شرط (۱) را با یک لایه‌ی اضافه‌تر حتی سخت‌گیرانه‌تر می‌کند:

  1. پیام باید از طرف خودِ اکانت لاگین‌شده باشد (event.out == True) — دقیقاً
     مثل قبل. یعنی هیچ‌کس دیگری، در هیچ گروه/پی‌وی/کانالی، هرگز نمی‌تواند
     دستوری اجرا کند؛ فقط پیام‌هایی که *خودت* تایپ و ارسال می‌کنی بررسی
     می‌شوند.
  2. به‌علاوه، اگر متغیر محیطی OWNER_ID تنظیم شده باشد، آیدی عددی فرستنده با
     آن مقایسه و باید دقیقاً برابر باشد (یک لایه‌ی دفاعی اضافه در برابر حالت
     نادر session hijack که event.out ممکن است دستکاری شده باشد).
  3. اگر OWNER_ID در Railway Variables تنظیم نشده باشد، این پلاگین به‌طور
     خودکار و امن، آیدی واقعی اکانت لاگین‌شده (get_me) را در اولین اجرا
     می‌خواند و همان را به‌عنوان owner در نظر می‌گیرد — نیازی به تنظیم دستی
     نیست، اما تنظیم صریح OWNER_ID در Railway همیشه توصیه می‌شود.

نحوه‌ی فعال/غیرفعال کردن:
  - برای بازگشت به حالت قبل (فقط Saved Messages)، کافی است همین یک فایل را
    از پوشه‌ی plugins/ حذف کنی (یا با .reload آن را غیرفعال نکنی). هیچ فایل
    دیگری دست‌نخورده باقی می‌ماند.

نکته درباره‌ی ترتیب بارگذاری:
  نام فایل عمداً با پیشوند «aa_» شروع شده تا در بارگذاری الفبایی پلاگین‌ها
  (در plugin_loader.py) زودتر از بقیه بارگذاری شود؛ این تضمین می‌کند که وقتی
  پلاگین‌های دیگر تابع is_authorized را از ماژول security می‌خوانند، نسخه‌ی
  جایگزین‌شده را دریافت کنند.
"""

import logging
import os

import security

logger = logging.getLogger("selfbot.owner_wide_access")

# اگر در Railway Variables تنظیم شده باشد، همین مقدار معیار owner است.
_ENV_OWNER_ID = os.environ.get("OWNER_ID", "").strip()

# کش داخلی آیدی owner (در صورت نبودن OWNER_ID، از get_me() پر می‌شود)
_resolved_owner_id = int(_ENV_OWNER_ID) if _ENV_OWNER_ID.isdigit() else None


async def _new_is_authorized(event) -> bool:
    """
    نسخه‌ی جایگزین‌شده‌ی is_authorized: دستور از هر چتی مجاز است، به شرطی که:
      - پیام واقعاً توسط خودِ اکانت لاگین‌شده ارسال شده باشد (event.out).
      - آیدی فرستنده با OWNER_ID (یا آیدی get_me در نبود آن) مطابقت داشته باشد.
    """
    global _resolved_owner_id
    try:
        if not event.out:
            # پیام از طرف کس دیگری است -> هرگز اجازه نده. این خط تغییرناپذیر است.
            return False

        if _resolved_owner_id is None:
            me = await event.client.get_me()
            _resolved_owner_id = me.id
            logger.info(
                "OWNER_ID به‌صورت خودکار از get_me() تشخیص داده شد: %s",
                _resolved_owner_id,
            )

        sender_id = event.sender_id
        if sender_id != _resolved_owner_id:
            return False

        return True
    except Exception:
        # در هر حالت نامشخص یا خطا، محافظه‌کارانه رفتار کن: اجازه نده.
        return False


async def register(client):
    # ------------------------------------------------------------------
    # نکته‌ی فنی مهم: پلاگین‌های دیگر تابع را با
    #   from security import is_authorized
    # وارد کرده‌اند، یعنی هرکدام یک ارجاع (reference) مستقل به همان آبجکت
    # تابع دارند، نه به خودِ ماژول security. بنابراین اگر فقط این خط را
    # بنویسیم:
    #   security.is_authorized = _new_is_authorized
    # آن پلاگین‌ها همچنان به تابع قدیمی اشاره می‌کنند و تغییری نمی‌بینند.
    #
    # راه‌حلِ صحیح و امن: به‌جای جایگزین کردن ارجاع، محتوای اجرایی
    # (__code__ و __globals__) خودِ همان آبجکت تابع قدیمی را با تابع جدید
    # عوض می‌کنیم. چون همه‌ی پلاگین‌ها (قدیمی و جدید) به یک آبجکت واحد در
    # حافظه اشاره می‌کنند، این روش برای همه یکسان و بلافاصله اعمال می‌شود؛
    # هیچ فایلی روی دیسک تغییر نمی‌کند و در ری‌استارت بعدی هم دوباره از نو
    # (به همین شکل، توسط همین پلاگین) اعمال می‌شود.
    # ------------------------------------------------------------------
    security.is_authorized.__code__ = _new_is_authorized.__code__
    security.is_authorized.__globals__.update(_new_is_authorized.__globals__)

    logger.warning(
        "⚠️ سیاست امنیتی تغییر کرد: دستورات اکنون از هر چتی (نه فقط Saved "
        "Messages) پذیرفته می‌شوند، اما فقط اگر خودِ owner (بر اساس OWNER_ID "
        "یا آیدی اکانت لاگین‌شده) آن‌ها را ارسال کرده باشد."
    )
